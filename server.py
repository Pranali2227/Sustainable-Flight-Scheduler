def get_pool() -> oracledb.ConnectionPool:
    global _pool
    if _pool is None:
        user = os.getenv("ORACLE_USER")
        password = os.getenv("ORACLE_PASSWORD")
        dsn = os.getenv("ORACLE_DSN")
        if not user or not password or not dsn:
            raise HTTPException(status_code=503, detail="Set ORACLE_USER, ORACLE_PASSWORD, and ORACLE_DSN in the local .env file.")
        try:
            _pool = oracledb.create_pool(user=user, password=password, dsn=dsn, min=1, max=4, increment=1)
        except oracledb.Error as exc:
            raise HTTPException(status_code=503, detail=f"Oracle connection failed: {exc}") from exc
    return _pool


@contextmanager
def connection():
    try:
        conn = get_pool().acquire()
    except oracledb.Error as exc:
        raise HTTPException(status_code=503, detail=f"Cannot acquire an Oracle connection: {exc}") from exc
    try:
        yield conn
    finally:
        conn.close()


def rows_as_dicts(cursor: oracledb.Cursor) -> list[dict[str, Any]]:
    names = [column[0].lower() for column in cursor.description]
    result = []
    for row in cursor:
        item = dict(zip(names, row))
        for key, value in item.items():
            if isinstance(value, (datetime, date)):
                item[key] = value.isoformat()
        result.append(item)
    return result


def ensure_auth_table() -> None:
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = :table_name", {"table_name": AUTH_TABLE})
            if cursor.fetchone()[0]:
                return
            try:
                cursor.execute(f"""CREATE TABLE {AUTH_TABLE} (
                    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    NAME VARCHAR2(80) NOT NULL,
                    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
                    PASSWORD_HASH VARCHAR2(256) NOT NULL,
                    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
                )""")
            except oracledb.DatabaseError as exc:
                if getattr(exc.args[0], "code", None) != 955:
                    raise


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=2**14, r=8, p=1, dklen=64)
    return f"scrypt$16384$8$1${base64.urlsafe_b64encode(salt).decode()}${base64.urlsafe_b64encode(digest).decode()}"


def verify_password(password: str, encoded: str) -> bool:
    try:
        algorithm, n, r, p, salt_text, digest_text = encoded.split("$", 5)
        if algorithm != "scrypt":
            return False
        salt = base64.urlsafe_b64decode(salt_text.encode())
        expected = base64.urlsafe_b64decode(digest_text.encode())
        actual = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=int(n), r=int(r), p=int(p), dklen=len(expected))
        return hmac.compare_digest(actual, expected)
    except (ValueError, TypeError):
        return False


def get_session_secret() -> bytes:
    global _session_secret
    if _session_secret is None:
        path = ROOT / ".session_secret"
        try:
            _session_secret = path.read_bytes()
        except FileNotFoundError:
            _session_secret = secrets.token_bytes(32)
            try:
                with path.open("xb") as secret_file:
                    secret_file.write(_session_secret)
            except FileExistsError:
                _session_secret = path.read_bytes()
    return _session_secret


def create_session(user: dict[str, Any]) -> str:
    payload = {"id": user["user_id"], "name": user["name"], "email": user["email"], "exp": int(datetime.now().timestamp()) + SESSION_SECONDS}
    encoded = base64.urlsafe_b64encode(json.dumps(payload, separators=(",", ":")).encode()).rstrip(b"=")
    signature = hmac.new(get_session_secret(), encoded, hashlib.sha256).digest()
    return f"{encoded.decode()}.{base64.urlsafe_b64encode(signature).rstrip(b'=').decode()}"


def session_user(request: Request) -> dict[str, Any] | None:
    token = request.cookies.get(SESSION_COOKIE)
    if not token or "." not in token:
        return None
    encoded_text, signature_text = token.rsplit(".", 1)
    encoded = encoded_text.encode()
    expected = hmac.new(get_session_secret(), encoded, hashlib.sha256).digest()
    try:
        supplied = base64.urlsafe_b64decode(signature_text + "=" * (-len(signature_text) % 4))
        payload_bytes = base64.urlsafe_b64decode(encoded_text + "=" * (-len(encoded_text) % 4))
        payload = json.loads(payload_bytes)
    except (ValueError, json.JSONDecodeError):
        return None
    if not hmac.compare_digest(expected, supplied) or payload.get("exp", 0) < datetime.now().timestamp():
        return None
    return payload


def require_user(request: Request) -> dict[str, Any]:
    user = session_user(request)
    if user is None:
        raise HTTPException(status_code=401, detail="Please sign in to continue.")
    return user


def flight_label(flight_id: int | None) -> str:
    return f"NS {flight_id:03d}" if flight_id is not None else "—"


def read_all() -> dict[str, list[dict[str, Any]]]:
    queries = {
        "flights": """SELECT f.FLIGHT_ID AS db_id, f.ROUTE_CODE AS route,
            TO_CHAR(f.DEP_TIME, 'YYYY-MM-DD\"T\"HH24:MI:SS') AS departure_iso,
            TO_CHAR(f.DEP_TIME, 'HH24:MI') AS departure,
            TO_CHAR(f.ARR_TIME, 'YYYY-MM-DD\"T\"HH24:MI:SS') AS arrival_iso,
            TO_CHAR(f.ARR_TIME, 'HH24:MI') AS arrival,
            f.AIRCRAFT_ID AS aircraft_id, a.MODEL AS model, f.FLIGHT_STATUS AS status
            FROM FLIGHT f JOIN AIRCRAFT a ON a.AIRCRAFT_ID = f.AIRCRAFT_ID ORDER BY f.DEP_TIME""",
        "fleet": """SELECT a.AIRCRAFT_ID AS db_id, a.MODEL AS model, a.CAPACITY_KG AS capacity_kg,
            a.FUEL_EFFICIENCY AS efficiency, a.AIRCRAFT_STATUS AS status,
            (SELECT MIN(f.FLIGHT_ID) FROM FLIGHT f WHERE f.AIRCRAFT_ID = a.AIRCRAFT_ID) AS flight_id
            FROM AIRCRAFT a ORDER BY a.AIRCRAFT_ID""",
        "crew": """SELECT c.CREW_ID AS db_id, c.CREW_NAME AS name, c.ROLE AS role,
            c.BASE_LOCATION AS base, fc.FLIGHT_ID AS flight_id, fc.SHIFT_HOURS AS shift
            FROM CREW c LEFT JOIN (SELECT CREW_ID, MIN(FLIGHT_ID) AS FLIGHT_ID,
            MIN(SHIFT_HOURS) AS SHIFT_HOURS FROM FLIGHT_CREW GROUP BY CREW_ID) fc
            ON fc.CREW_ID = c.CREW_ID ORDER BY c.CREW_ID""",
        "cargo": """SELECT c.CARGO_ID AS db_id, c.CARGO_DESCRIPTION AS name, c.CATEGORY AS category,
            c.FLIGHT_ID AS flight_id, c.WEIGHT_KG AS weight_kg, c.REQ_TEMP_C AS required_temp_c,
            c.CURRENT_TEMP_C AS current_temp_c, c.TRACKING_STATUS AS tracking
            FROM SPEC_CARGO c ORDER BY c.CARGO_ID""",
        "passengers": """SELECT p.PASSENGER_ID AS db_id, p.PASSENGER_NAME AS name,
            p.PASSPORT_NO AS passport_no,
            p.TIER_ID AS tier_id, lt.TIER_NAME AS tier, lt.EXTRA_BAGGAGE_KG AS allowance_kg,
            p.BAGGAGE_KG AS baggage_kg,
            (SELECT MIN(b.FLIGHTNO) FROM BOOKING b WHERE b.P_ID = TO_CHAR(p.PASSENGER_ID)) AS flight_id
            FROM PASSENGER p JOIN LOYALTY_TIER lt ON lt.TIER_ID = p.TIER_ID ORDER BY p.PASSENGER_ID""",
        "disruptions": """SELECT d.EVENT_ID AS db_id, d.FLIGHT_ID AS flight_id, f.ROUTE_CODE AS route,
            d.REASON_CODE AS reason, d.DELAY_MIN AS delay_min,
            TO_CHAR(d.EVENT_DATE, 'YYYY-MM-DD\"T\"HH24:MI:SS') AS event_date,
            d.EVENT_STATUS AS status FROM DISRUPTION d JOIN FLIGHT f ON f.FLIGHT_ID = d.FLIGHT_ID
            ORDER BY d.EVENT_DATE DESC""",
        "emissions": """SELECT e.LOG_ID AS db_id, e.FLIGHT_ID AS flight_id, f.ROUTE_CODE AS route,
            e.FUEL_LITERS AS fuel_liters, e.CO2_TONS AS co2_tons, f.AIRCRAFT_ID AS aircraft_id,
            TO_CHAR(e.LOGGED_AT, 'YYYY-MM-DD\"T\"HH24:MI:SS') AS logged_at
            FROM EMISSIONS e JOIN FLIGHT f ON f.FLIGHT_ID = e.FLIGHT_ID ORDER BY e.LOGGED_AT DESC""",
        "loyalty_tiers": "SELECT TIER_ID AS tier_id, TIER_NAME AS tier_name, EXTRA_BAGGAGE_KG AS allowance_kg FROM LOYALTY_TIER ORDER BY TIER_ID",
    }
    result: dict[str, list[dict[str, Any]]] = {}
    with connection() as conn:
        with conn.cursor() as cursor:
            for entity, sql in queries.items():
                cursor.execute(sql)
                records = rows_as_dicts(cursor)
                if entity == "flights":
                    for row in records:
                        row.update(id=flight_label(row["db_id"]), aircraft=f"AC-{row['aircraft_id']:03d} · {row['model']}")
                elif entity == "fleet":
                    for row in records:
                        row.update(id=f"AC-{row['db_id']:03d}", capacity=f"{row['capacity_kg']:,.0f} kg", efficiency=f"{row['efficiency']} L / 100 km", flights=flight_label(row["flight_id"]) if row["flight_id"] else "—")
                elif entity == "crew":
                    for row in records:
                        row.update(id=f"CR-{row['db_id']:03d}", flight=flight_label(row["flight_id"]) if row["flight_id"] else "—", shift=f"{row['shift']} h" if row["shift"] is not None else "—", status="On duty" if row["flight_id"] else "Standby")
                elif entity == "cargo":
                    for row in records:
                        row.update(id=f"CG-{row['db_id']:04d}", flight=flight_label(row["flight_id"]), weight=f"{row['weight_kg']:,.0f} kg", required=f"{row['required_temp_c']} °C" if row["required_temp_c"] is not None else "Not specified", current=f"{row['current_temp_c']} °C" if row["current_temp_c"] is not None else "Not recorded")
                elif entity == "passengers":
                    for row in records:
                        row.update(id=f"P-{row['db_id']:05d}", allowance=f"+{row['allowance_kg']:g} kg", baggage=f"{row['baggage_kg']:g} kg", flight=flight_label(row["flight_id"]) if row["flight_id"] else "—")
                elif entity == "disruptions":
                    for row in records:
                        row.update(id=f"DP-{row['db_id']:04d}", flight=flight_label(row["flight_id"]), delay=f"{row['delay_min']} min", date=row["event_date"])
                elif entity == "emissions":
                    for row in records:
                        row.update(id=f"EM-{row['db_id']:04d}", flight=flight_label(row["flight_id"]), fuel=f"{row['fuel_liters']:,.0f} L", co2=f"{row['co2_tons']:g} t", aircraft=f"AC-{row['aircraft_id']:03d}", logged=row["logged_at"])
                result[entity] = records
    return result


@app.get("/api/health")
def health() -> dict[str, Any]:
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("SELECT USER, SYS_CONTEXT('USERENV','SERVICE_NAME'), SYS_CONTEXT('USERENV','CON_NAME') FROM DUAL")
            user, service, container = cursor.fetchone()
            cursor.execute("SELECT TABLE_NAME FROM USER_TABLES")
            visible = {row[0] for row in cursor.fetchall()}
    required = {"AIRCRAFT", "CREW", "DISRUPTION", "EMISSIONS", "FLIGHT", "LOYALTY_TIER", "PASSENGER", "SPEC_CARGO"}
    missing = sorted(required - visible)
    if missing:
        raise HTTPException(status_code=503, detail=f"Oracle is reachable as {user} on {service}/{container}, but this schema cannot see the airline tables. Use the same Oracle username and service as the SQL*Plus session where you ran the inserts.")
    return {"status": "ok", "database": "Oracle", "user": user, "service": service, "container": container}


@app.post("/api/auth/signup", status_code=201)
def signup(payload: dict[str, Any], response: Response) -> dict[str, Any]:
    name = str(payload.get("name", "")).strip()
    email = str(payload.get("email", "")).strip().lower()
    password = str(payload.get("password", ""))
    if not name or len(name) > 80:
        raise HTTPException(status_code=422, detail="Name is required and must be 80 characters or fewer.")
    if not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email) or len(email) > 254:
        raise HTTPException(status_code=422, detail="Enter a valid email address.")
    if len(password) < 10:
        raise HTTPException(status_code=422, detail="Password must be at least 10 characters.")
    ensure_auth_table()
    try:
        with connection() as conn:
            with conn.cursor() as cursor:
                user_id_var = cursor.var(oracledb.NUMBER)
                cursor.execute(
                    f"INSERT INTO {AUTH_TABLE} (NAME, EMAIL, PASSWORD_HASH) VALUES (:name, :email, :password_hash) RETURNING USER_ID INTO :user_id",
                    {"name": name, "email": email, "password_hash": hash_password(password), "user_id": user_id_var},
                )
                user_id = user_id_var.getvalue()
                conn.commit()
    except oracledb.DatabaseError as exc:
        if getattr(exc.args[0], "code", None) == 1:
            raise HTTPException(status_code=409, detail="An account with this email already exists.") from exc
        raise HTTPException(status_code=503, detail="Could not create the account in Oracle.") from exc
    if isinstance(user_id, list):
        user_id = user_id[0]
    user = {"user_id": int(user_id), "name": name, "email": email}
    response.set_cookie(SESSION_COOKIE, create_session(user), httponly=True, samesite="lax", secure=False, max_age=SESSION_SECONDS, path="/")
    return user


@app.post("/api/auth/login")
def login(payload: dict[str, Any], response: Response) -> dict[str, Any]:
    email = str(payload.get("email", "")).strip().lower()
    password = str(payload.get("password", ""))
    ensure_auth_table()
    try:
        with connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(f"SELECT USER_ID, NAME, EMAIL, PASSWORD_HASH FROM {AUTH_TABLE} WHERE EMAIL = :email", {"email": email})
                row = cursor.fetchone()
    except oracledb.DatabaseError as exc:
        raise HTTPException(status_code=503, detail="Could not check the account in Oracle.") from exc
    if row is None or not verify_password(password, row[3]):
        raise HTTPException(status_code=401, detail="Email or password is incorrect.")
    user = {"user_id": int(row[0]), "name": row[1], "email": row[2]}
    response.set_cookie(SESSION_COOKIE, create_session(user), httponly=True, samesite="lax", secure=False, max_age=SESSION_SECONDS, path="/")
    return user


