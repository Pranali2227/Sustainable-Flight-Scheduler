def get_entity(entity: str) -> dict[str, Any]:
    definition = ENTITIES.get(entity)
    if definition is None:
        raise HTTPException(status_code=404, detail="Unknown entity.")
    return definition


def write_record(entity: str, key_value: int | str | None, payload: dict[str, Any], create: bool) -> dict[str, Any]:
    definition = get_entity(entity)
    fields: dict[str, str] = definition["fields"]
    provided_key = payload.pop("db_id", None) if create else None
    unknown = set(payload) - set(fields)
    if unknown:
        raise HTTPException(status_code=422, detail=f"Unsupported fields: {', '.join(sorted(unknown))}")
    if provided_key is not None:
        try:
            provided_key = int(provided_key)
        except (TypeError, ValueError) as exc:
            raise HTTPException(status_code=422, detail="db_id must be a number.") from exc
    if not payload:
        raise HTTPException(status_code=422, detail="Provide at least one field.")
    columns = list(payload)
    binds = {name: payload[name] for name in columns}
    date_fields = {"departure", "arrival", "event_date", "logged_at"}
    for name in columns:
        if name in date_fields and binds[name] is not None:
            try:
                binds[name] = datetime.fromisoformat(str(binds[name]))
            except ValueError as exc:
                raise HTTPException(status_code=422, detail=f"{name} must be an ISO date/time.") from exc
    if binds.get("departure") is not None and binds.get("arrival") is not None and binds["arrival"] <= binds["departure"]:
        raise HTTPException(status_code=422, detail="Arrival must be after departure.")
    try:
        with connection() as conn:
            with conn.cursor() as cursor:
                if create:
                    column_sql = ", ".join(fields[name] for name in columns)
                    bind_sql = ", ".join(f":{name}" for name in columns)
                    if provided_key is not None:
                        column_sql = f"{definition['key']}, {column_sql}"
                        bind_sql = f":provided_key, {bind_sql}"
                        binds["provided_key"] = provided_key
                    key_var = cursor.var(oracledb.NUMBER)
                    sql = f"INSERT INTO {definition['table']} ({column_sql}) VALUES ({bind_sql}) RETURNING {definition['key']} INTO :new_key"
                    cursor.execute(sql, {**binds, "new_key": key_var})
                    new_key = key_var.getvalue()
                    conn.commit()
                    return {"db_id": new_key, "message": "Created"}
                assignments = ", ".join(f"{fields[name]} = :{name}" for name in columns)
                binds["record_key"] = key_value
                cursor.execute(f"UPDATE {definition['table']} SET {assignments} WHERE {definition['key']} = :record_key", binds)
                if cursor.rowcount == 0:
                    raise HTTPException(status_code=404, detail="Record not found.")
                conn.commit()
                return {"db_id": key_value, "message": "Updated"}
    except HTTPException:
        raise
    except oracledb.Error as exc:
        raise HTTPException(status_code=409, detail=f"Oracle rejected the change. Check required fields, relationships, and generated IDs: {exc}") from exc


@app.post("/api/{entity}", status_code=201)
def create_record(entity: str, payload: dict[str, Any], _user: dict[str, Any] = Depends(require_user)) -> dict[str, Any]:
    return write_record(entity, None, payload, True)


@app.put("/api/{entity}/{record_id}")
def update_record(entity: str, record_id: str, payload: dict[str, Any], _user: dict[str, Any] = Depends(require_user)) -> dict[str, Any]:
    definition = get_entity(entity)
    try:
        key_value: int | str = int(record_id) if definition["key"] != "BOOKING_ID" else record_id
    except ValueError as exc:
        raise HTTPException(status_code=422, detail="Record ID must be numeric.") from exc
    return write_record(entity, key_value, payload, False)


def delete_flight_dependents(cursor: oracledb.Cursor, flight_ids_sql: str, binds: dict[str, Any]) -> int:
    deleted = 0
    for table in ("DISRUPTION", "EMISSIONS", "FLIGHT_CREW", "SPEC_CARGO"):
        cursor.execute(f"DELETE FROM {table} WHERE FLIGHT_ID IN ({flight_ids_sql})", binds)
        deleted += cursor.rowcount
    return deleted


@app.delete("/api/{entity}/{record_id}")
def delete_record(entity: str, record_id: str, _user: dict[str, Any] = Depends(require_user)) -> dict[str, Any]:
    definition = get_entity(entity)
    try:
        key_value = int(record_id)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail="Record ID must be numeric.") from exc
    try:
        with connection() as conn:
            with conn.cursor() as cursor:
                related_deleted = 0
                if definition["table"] == "FLIGHT":
                    related_deleted = delete_flight_dependents(
                        cursor, "SELECT FLIGHT_ID FROM FLIGHT WHERE FLIGHT_ID = :record_key", {"record_key": key_value}
                    )
                elif definition["table"] == "AIRCRAFT":
                    flight_ids_sql = "SELECT FLIGHT_ID FROM FLIGHT WHERE AIRCRAFT_ID = :record_key"
                    related_deleted = delete_flight_dependents(cursor, flight_ids_sql, {"record_key": key_value})
                    cursor.execute("DELETE FROM FLIGHT WHERE AIRCRAFT_ID = :record_key", {"record_key": key_value})
                    related_deleted += cursor.rowcount
                elif definition["table"] == "CREW":
                    cursor.execute("DELETE FROM FLIGHT_CREW WHERE CREW_ID = :record_key", {"record_key": key_value})
                    related_deleted = cursor.rowcount
                cursor.execute(f"DELETE FROM {definition['table']} WHERE {definition['key']} = :record_key", {"record_key": key_value})
                if cursor.rowcount == 0:
                    raise HTTPException(status_code=404, detail="Record not found.")
                conn.commit()
        return {"message": "Deleted", "related_deleted": related_deleted}
    except HTTPException:
        raise
    except oracledb.Error as exc:
        raise HTTPException(status_code=409, detail=f"Oracle rejected the delete, possibly because related records exist: {exc}") from exc


@app.get("/")
def index() -> FileResponse:
    return FileResponse(ROOT / "index.html")


@app.get("/{asset_path:path}")
def static_files(asset_path: str) -> FileResponse:
    path = (ROOT / asset_path).resolve()
    if ROOT not in path.parents or not path.is_file():
        raise HTTPException(status_code=404, detail="Not found.")
    return FileResponse(path)
